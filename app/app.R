suppressPackageStartupMessages({
  library(shiny); library(bslib); library(dplyr); library(ggplot2); library(DT)
})

dat <- readRDS(file.path(if (file.exists("dashboard_data.rds")) "." else "app", "dashboard_data.rds"))
results <- dat$results
log <- dat$cleaning_log
labels <- results %>% distinct(indicator, label)
ind_choices <- setNames(labels$indicator, labels$label)

pct <- function(x) sprintf("%.0f%%", 100 * x)
col_idp <- "#C8553D"; col_host <- "#2B6F8E"; col_all <- "#4A4A4A"

ui <- page_navbar(
  title = "Somalia Household Survey Dashboard",
  theme = bs_theme(version = 5, primary = "#2B6F8E", base_font = font_collection("Segoe UI", "Arial", "sans-serif")),
  nav_panel(
    "Overview",
    div(class = "alert alert-warning py-2",
        "Demonstration only: all figures come from synthetic data generated by this project."),
    layout_columns(
      col_widths = c(4, 4, 4),
      !!!lapply(c("ind_fcs_poor_borderline", "ind_rcsi_high", "ind_water_15l"), function(ind) {
        r <- results %>% filter(level == "Overall", indicator == ind)
        value_box(title = r$label, value = pct(r$estimate),
                  p(sprintf("95%% CI %s - %s", pct(r$low), pct(r$high))))
      })
    ),
    card(card_header("IDP and host households, all indicators"),
         plotOutput("gap_plot", height = "420px"))
  ),
  nav_panel(
    "Explore by area",
    layout_sidebar(
      sidebar = sidebar(
        selectInput("indicator", "Indicator", ind_choices),
        radioButtons("level", "Break down by", c("District", "Stratum")),
        helpText("Bars show weighted estimates; lines show 95% confidence intervals",
                 "that account for stratification and clustering.")
      ),
      card(plotOutput("area_plot", height = "460px")),
      card(DTOutput("area_table"))
    )
  ),
  nav_panel(
    "Data quality",
    layout_columns(
      col_widths = c(5, 7),
      card(card_header("Issues found and decisions taken"), plotOutput("qa_plot", height = "360px")),
      card(card_header("Cleaning log"), DTOutput("log_table"))
    )
  ),
  nav_panel(
    "Methodology",
    card(markdown("
**Sampling.** Stratified two-stage cluster sample: 4 districts x 2 population groups (IDP, host) = 8 strata;
8 clusters per stratum and 12 households per cluster.

**Weighting.** Design weight = households in stratum / households interviewed in stratum.
Weighted totals are checked against the population frame.

**Analysis.** `survey::svydesign(ids = ~cluster_id, strata = ~strata, weights = ~weight)`; proportions and
95% confidence intervals with `svymean` and `svyby`.

**Indicators.** Food Consumption Score (WFP weights; poor <= 21, borderline 21.5-35), reduced Coping Strategies
Index (high >= 19), water source and quantity (15 litres per person per day), shelter type, assistance received.

**Cleaning.** Duplicates, interviews under 15 minutes, IQR outliers, logic errors and 'other' answers are
flagged; each decision is recorded in the cleaning log and verified after it is applied.

**Data.** Synthetic, generated by `R/00_simulate_kobo_data.R`. No real respondents.
"))
  )
)

server <- function(input, output, session) {

  output$gap_plot <- renderPlot({
    d <- results %>% filter(level == "Population group") %>%
      mutate(group = recode(group, idp = "IDP", host = "Host"),
             label = reorder(label, estimate))
    ggplot(d, aes(estimate, label, colour = group)) +
      geom_line(aes(group = label), colour = "grey75", linewidth = 1.2) +
      geom_errorbarh(aes(xmin = low, xmax = high), height = 0.2, alpha = 0.6) +
      geom_point(size = 3.5) +
      scale_x_continuous(labels = scales::percent, limits = c(0, 1)) +
      scale_colour_manual(values = c(IDP = col_idp, Host = col_host)) +
      labs(x = "Weighted % of households (95% CI)", y = NULL, colour = NULL) +
      theme_minimal(base_size = 14) + theme(legend.position = "top")
  })

  area_data <- reactive({
    results %>% filter(level == input$level, indicator == input$indicator) %>%
      mutate(pop_group = case_when(grepl("_idp$", group) ~ "IDP",
                                   grepl("_host$", group) ~ "Host", TRUE ~ "All"),
             group = sub("_idp$", " - IDP", sub("_host$", " - Host", group)),
             group = reorder(group, estimate))
  })

  output$area_plot <- renderPlot({
    d <- area_data()
    ggplot(d, aes(estimate, group, fill = pop_group)) +
      geom_col(width = 0.65) +
      geom_errorbarh(aes(xmin = low, xmax = high), height = 0.25, colour = "grey25") +
      geom_text(aes(x = high, label = pct(estimate)), hjust = -0.2, size = 4.5) +
      scale_x_continuous(labels = scales::percent, limits = c(0, 1.1), breaks = seq(0, 1, .25)) +
      scale_fill_manual(values = c(IDP = col_idp, Host = col_host, All = col_all)) +
      labs(title = names(ind_choices)[ind_choices == input$indicator],
           x = "Weighted % of households", y = NULL, fill = NULL) +
      theme_minimal(base_size = 14) + theme(legend.position = "top")
  })

  output$area_table <- renderDT({
    area_data() %>% arrange(desc(estimate)) %>%
      transmute(Area = as.character(group), Estimate = pct(estimate),
                `95% CI` = paste(pct(low), "-", pct(high))) %>%
      datatable(rownames = FALSE, options = list(dom = "t", pageLength = 20))
  })

  output$qa_plot <- renderPlot({
    log %>% count(check_id, change_type) %>%
      ggplot(aes(n, reorder(check_id, n), fill = change_type)) +
      geom_col() +
      labs(x = "Number of flags", y = NULL, fill = "Decision") +
      theme_minimal(base_size = 13) + theme(legend.position = "bottom")
  })

  output$log_table <- renderDT({
    datatable(log, rownames = FALSE, filter = "top", options = list(pageLength = 10, scrollX = TRUE))
  })
}

shinyApp(ui, server)
